export const HERO_GAP = 2.7; // between glyph boxes: the widest outline pass is ~2 units, so this leaves a sliver of air
export const HERO_SPACE = 3.2;
const FALLBACK = H['?'];
const paths = new Map();

/** Path2D of one hero glyph in its own units (x 0..w, y 0..6) and its box width. */
export function heroGlyph(ch) {
  let p = paths.get(ch);
  if (p) return p;
  const d = H[ch] || H[ch.toUpperCase()] || FALLBACK;
  const path = new Path2D();
  for (let i = 1; i < d.length; i++) {
    const pl = d[i];
    path.moveTo(pl[0][0], pl[0][1]);
    for (let j = 1; j < pl.length; j++) path.lineTo(pl[j][0], pl[j][1]);
    if (pl.length === 2 && pl[0][0] === pl[1][0] && pl[0][1] === pl[1][1]) path.lineTo(pl[0][0] + 0.001, pl[0][1]);
  }
  p = { path, w: d[0] };
  paths.set(ch, p);
  return p;
}

const layouts = new Map();
/** {glyphs: [{ch, x, w, path}], width} — x is the glyph's left edge in glyph units; width excludes outline overhang. */
export function heroLayout(text) {
  let l = layouts.get(text);
  if (l) return l;
  const glyphs = [];
  let x = 0;
  for (const raw of text) {
    if (raw === ' ') { x += HERO_SPACE; continue; }
    const ch = raw.toUpperCase();
    const gl = heroGlyph(ch);
    glyphs.push({ ch, x, w: gl.w, path: gl.path });
    x += gl.w + HERO_GAP;
  }
  l = { glyphs, width: Math.max(0, x - HERO_GAP) };
  layouts.set(text, l);
  return l;
}

