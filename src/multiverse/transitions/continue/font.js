export const bitsWidth = (str, cell) => Math.max(0, str.length * 6 - 1) * cell;

/**
 * Dot-matrix text. (x, y) is the top-left (align 'l'), top-centre ('c') or top-right ('r') of
 * the first line; `cell` is one dot in px (use whole numbers: the dots stay crisp). One path,
 * one fill: cheap even for long lines.
 */
export function drawBits(g, str, x, y, cell, color, align = 'l', shadow = null, snap = 1) {
  str = String(str).toUpperCase();
  const w = bitsWidth(str, cell);
  let ox = align === 'c' ? x - w / 2 : align === 'r' ? x - w : x;
  ox = Math.round(ox * snap) / snap;
  y = Math.round(y * snap) / snap;
  for (let pass = shadow ? 0 : 1; pass < 2; pass++) {
    g.fillStyle = pass ? color : shadow.color;
    const off = pass ? 0 : shadow.d * cell;
    g.beginPath();
    for (let i = 0; i < str.length; i++) {
      const cells = BITS.get(str[i]) || BITS.get('?');
      const cx = ox + i * 6 * cell + off, cy = y + off;
      for (let j = 0; j < cells.length; j += 2) g.rect(cx + cells[j] * cell, cy + cells[j + 1] * cell, cell, cell);
    }
    g.fill();
  }
  return w;
}

